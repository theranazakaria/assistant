async function schemaOk() {
  const m = await q("SELECT 1 AS x FROM information_schema.tables WHERE table_name='meta' AND table_schema='public'");
  if (!m.length) return false;
  const v = await q("SELECT v FROM meta WHERE k='schema'");
  return !!(v[0] && v[0].v === SCHEMA);
}
